"""Paired McNemar tests for the whitepaper, from saved per-shot error bits only (no new evals).

    cd <repo root> && python whitepaper/paired_tests.py      # writes whitepaper/paired_tests.md

Inputs (all existing files):
- results/exp6/d5/st{0..4}/ens_<type>_errors.npz : packed per-shot error bits of the d=5 three-seed
  ensembles, key "<regime>|live|ens" or "<regime>|frozen|ens", 150 steps x 2000 shots in stream order.
- results/exp3/d5/<regime>_d5_r5_u200_st{0..4}_s0.csv : the noise state of every step, used for the
  drift-step mask (same definition as eval.phase_masks: drift = scale != 1 or any hot qubit).

Test: exact two-sided McNemar on shared shots (same sum as report.mcnemar_p), kept in log space so
that very small p-values do not underflow. Streams 0-4 are pooled. The script first reproduces the
published ensemble drift LERs from these bits (assert) so the masks are known to be right.

1. adaptive-stale ensemble with frozen fingerprint vs static-wide ensemble, bursts_big drift steps.
2. adaptive-wide ensemble vs adaptive-stale ensemble (both live), drift steps of each regime.
"""
from __future__ import annotations

import csv
import os
from math import exp, lgamma, log

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REGIMES = ["bursts", "bursts_big", "hot_qubit", "telegraph"]
SHOTS = 2000


def drift_mask(regime, st):
    rows = list(csv.DictReader(open(os.path.join(ROOT, f"results/exp3/d5/{regime}_d5_r5_u200_st{st}_s0.csv"))))
    step = np.array([(float(r["scale"]) != 1.0) or int(r["n_hot"]) > 0 for r in rows])
    return np.repeat(step, SHOTS)


def bits(t, regime, kind):
    out = []
    for st in range(5):
        z = np.load(os.path.join(ROOT, f"results/exp6/d5/st{st}/ens_{t}_errors.npz"))
        b = np.unpackbits(z[f"{regime}|{kind}|ens"]).astype(bool)
        m = drift_mask(regime, st)
        out.append(b[: len(m)][m])
    return np.concatenate(out)


def mcnemar_log10(b, c):
    n, k = b + c, min(b, c)
    if n == 0:
        return 0.0
    logs = [lgamma(n + 1) - lgamma(i + 1) - lgamma(n - i + 1) - n * log(2) for i in range(k + 1)]
    m = max(logs)
    return min(0.0, (log(2) + m + log(sum(exp(x - m) for x in logs))) / log(10))


def p_str(lp):
    if lp > -300:
        return f"{10 ** lp:.2g}"
    e = int(np.floor(lp))
    return f"{10 ** (lp - e):.2g}e{e}"


def main():
    # check: these bits reproduce the published ensemble drift LERs (notes/07_ensembles.md, report6_tables.md)
    ref = {("adaptive_stale_d5_long", "live"): [0.0170, 0.0457, 0.0073, 0.0164],
           ("adaptive_wide_d5_long", "live"): [0.0171, 0.0484, 0.0071, 0.0164],
           ("static_wide_d5_long", "live"): [0.0224, 0.0564, 0.0098, 0.0175],
           ("adaptive_stale_d5_long", "frozen"): [0.0233, 0.0576, 0.0098, 0.0166]}
    for (t, kind), vals in ref.items():
        for r, v in zip(REGIMES, vals):
            got = bits(t, r, kind).mean()
            assert abs(got - v) < 5e-5, (t, kind, r, got, v)

    out = ["# Paired tests computed for the whitepaper", "",
           "Generated by `whitepaper/paired_tests.py` from saved per-shot error bits of the d=5 three-seed "
           "ensembles (`results/exp6/d5/st*/ens_*_errors.npz`) with drift-step masks from "
           "`results/exp3/d5/*_s0.csv`; streams 0-4 pooled. Exact two-sided McNemar on shared shots. "
           "b = shots only A gets wrong, c = shots only B gets wrong. The script first reproduces the published "
           "ensemble drift LERs from the same bits.", "",
           "| test | regime | LER A | LER B | A - B | b | c | shots | log10 p | p |",
           "|---|---|---|---|---|---|---|---|---|---|"]

    def row(name, r, a, b):
        na, nb = int((a & ~b).sum()), int((~a & b).sum())
        lp = mcnemar_log10(na, nb)
        out.append(f"| {name} | {r} | {a.mean():.4f} | {b.mean():.4f} | {(na - nb) / len(a):+.4f} | {na} | {nb} | "
                   f"{len(a)} | {lp:.1f} | {p_str(lp)} |")

    row("1. adaptive-stale ens. frozen (A) vs static-wide ens. (B)", "bursts_big",
        bits("adaptive_stale_d5_long", "bursts_big", "frozen"), bits("static_wide_d5_long", "bursts_big", "live"))
    for r in REGIMES:
        row("2. adaptive-wide ens. (A) vs adaptive-stale ens. (B)", r,
            bits("adaptive_wide_d5_long", r, "live"), bits("adaptive_stale_d5_long", r, "live"))
    path = os.path.join(ROOT, "whitepaper", "paired_tests.md")
    open(path, "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
